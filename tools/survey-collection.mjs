#!/usr/bin/env node
// Scores every counted 9x9 game in a collection of SGF files and saves the
// results for later reference: a JSON file (all fields) and a Markdown report.
// It resumes: games already in the JSON file are not scored again.
//
// Usage: node tools/survey-collection.mjs <collection-dir> <out-basename>
//   e.g. node tools/survey-collection.mjs ~/cwi/9x9 research/cwi-9x9-scoring
//   writes research/cwi-9x9-scoring.json and research/cwi-9x9-scoring.md
//
// Scoring is the same as tools/score-games.mjs (about 3 s per game).

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "fs";
import { join, relative } from "path";
import { analyse } from "./score-games.mjs";

const [root, out] = process.argv.slice(2);
if (!root || !out) { console.error("usage: node tools/survey-collection.mjs <collection-dir> <out-basename>"); process.exit(1); }

const walk = (d) => readdirSync(d).flatMap((f) => {
  const p = join(d, f);
  return statSync(p).isDirectory() ? walk(p) : f.toLowerCase().endsWith(".sgf") ? [p] : [];
});
const prop = (s, k) => (s.match(new RegExp("\\b" + k + "\\[([^\\]]*)\\]")) || [, ""])[1].trim();

const jsonPath = out + ".json";
const results = existsSync(jsonPath) ? JSON.parse(readFileSync(jsonPath, "utf8")) : [];
const done = new Set(results.map((r) => r.src));
const files = walk(root).sort();

let total = 0, notCounted = 0;
for (const f of files) {
  const t = readFileSync(f, "latin1");
  if (prop(t, "SZ") !== "9") continue;
  total++;
  if (!/^[BW]\+\d/.test(prop(t, "RE"))) { notCounted++; continue; }
  const src = relative(root, f);
  if (done.has(src)) continue;
  const r = analyse(t, "japanese");
  results.push({
    src, black: prop(t, "PB"), blackRank: prop(t, "BR"), white: prop(t, "PW"), whiteRank: prop(t, "WR"),
    date: prop(t, "DT"), event: prop(t, "EV"), komi: prop(t, "KM"), result: prop(t, "RE"),
    moves: r.game.moves.length, captures: { black: r.final.caps[1], white: r.final.caps[2] },
    method: r.method, matches: r.diff === r.target, count: r.diff, deadStones: r.deadStones, dead: r.dead, note: r.note,
  });
  writeFileSync(jsonPath, JSON.stringify(results, null, 1) + "\n");
  console.log(`${results.length} ${src}: ${r.method}`);
}
results.sort((a, b) => a.src.localeCompare(b.src));
writeFileSync(jsonPath, JSON.stringify(results, null, 1) + "\n");

// ---- Markdown report ----------------------------------------------------
const label = { "ownership": "Playouts", "ownership+neutral": "Playouts + neutral point", "ownership+result": "Playouts, fitted", "estimate": "No match" };
const count = (m) => results.filter((r) => r.method === m).length;
const fmt = (d) => (d === 0 ? "Jigo" : `${d > 0 ? "B" : "W"}+${Math.abs(d)}`);
const esc = (s) => String(s).replace(/\|/g, "\\|");
const row = (r) => `| ${esc(r.src)} | ${esc(r.black)}${r.blackRank ? " " + esc(r.blackRank) : ""} | ${esc(r.white)}${r.whiteRank ? " " + esc(r.whiteRank) : ""} | ${r.date} | ${r.komi || "–"} | ${r.result} | ${r.matches ? "✓" : fmt(r.count)} | ${r.moves} | ${r.captures.black}/${r.captures.white} | ${r.deadStones} | ${label[r.method] || r.method} |`;
const head = "| Source | Black | White | Date | Komi | Result | Count | Moves | Captures B/W | Dead | Method |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |";

const md = `# Scoring survey: CWI 9x9 collection

Generated by \`tools/survey-collection.mjs\` on ${new Date().toISOString().slice(0, 10)}. Full data, including notes, is in \`${relative(process.cwd(), jsonPath)}\`. Dead-stone points (\`dead\`) are stored for games scored by this tool; entries from the first run have \`dead: null\`, and \`tools/add-games.mjs\` recomputes them when a game is added (scoring is seeded, so the answer is the same).

The collection is the 9x9 set from Andries Brouwer's [Database of Go Games](https://homepages.cwi.nl/~aeb/go/games/) (\`9x9.tgz\`). Every game is scored with \`tools/score-games.mjs\` under Japanese rules: dead stones from 3,000 random playouts, then fitted to the recorded result if needed (see \`docs/games/9x9/pro/README.md\`).

## Summary

| | Games |
| --- | --- |
| 9x9 games in the collection | ${total} |
| Not a count (resignation, time, no result) | ${notCounted} |
| Counted games scored | ${results.length} |
| Matched by playouts alone | ${count("ownership")} |
| Matched after counting a neutral point | ${count("ownership+neutral")} |
| Matched after flipping groups the playouts were unsure about | ${count("ownership+result")} |
| No match (record probably unfinished) | ${count("estimate")} |

"Count" shows ✓ when the score matches the recorded result, otherwise the closest count found. Games already on the site are marked in \`docs/games/9x9/pro/index.json\`, not here.

## Counted games that didn't match

${head}
${results.filter((r) => !r.matches).map(row).join("\n")}

## All counted games

${head}
${results.map(row).join("\n")}
`;
writeFileSync(out + ".md", md);
console.log(`${results.length} games in ${jsonPath}; report in ${out}.md`);
